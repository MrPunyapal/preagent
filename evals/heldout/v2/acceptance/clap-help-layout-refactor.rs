use clap_builder::{Arg, Command};

#[test]
fn autogenerated_help_has_one_trailing_newline_and_all_sections() {
    let mut cmd = Command::new("fixture")
        .about("Exercise help formatting")
        .arg(Arg::new("verbose").long("verbose").short('v').help("Show details"))
        .subcommand(Command::new("inspect").about("Inspect the input"));
    let help = cmd.render_help().to_string();
    assert!(help.contains("--verbose"));
    assert!(help.contains("inspect"));
    assert!(help.ends_with('\n'), "help must end with newline");
    assert!(!help.ends_with("\n\n"), "help must not gain a redundant blank line");
}

#[test]
fn override_help_is_preserved_without_blank_lines() {
    let mut cmd = Command::new("fixture").override_help("CUSTOM HELP");
    assert_eq!(cmd.render_help().to_string(), "CUSTOM HELP\n");
}
